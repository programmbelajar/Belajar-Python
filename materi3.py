# TIPE DATA

# data integer  
data_int = 1
print("data: ", data_int, "\ntype: ", type(data_int), '\n')

# data float  
data_float = 1.5
print("data: ", data_float, "\ntype: ", type(data_float), '\n')

# data string
data_str = "Helloo guysss"
print("data: ", data_str, "\ntype: ", type(data_str), '\n')

# data boolean
data_bool = True
print("data: ", data_bool, "\ntype: ", type(data_bool), '\n')

# data complex
data_complex = complex(5, 6)
print("data: ", data_complex, "\ntype: ", type(data_complex), '\n')

# tipe data dari bahasa C
from ctypes import c_double
data_c_double = c_double(10.5)
print("data: ", data_c_double, "\ntype: ", type(data_c_double), '\n')
